# ── T69-1 canonical（幂等/追踪参剔除/大小写/fragment/默认端口）────────


def test_t69_1_canonical_idempotent_and_tracking_params() -> None:
    raw = "HTTPS://X.com:443/a?utm_source=rss&fbclid=1&gclid=2&q=keep#frag"
    canon = canonical_url(raw)
    assert canon == "https://x.com/a?q=keep"
    assert canonical_url(canon) == canon  # 幂等钉死
    # 非清单参不排序不剔除（保守清单）
    assert canonical_url("https://x.com/p?b=2&a=1") == "https://x.com/p?b=2&a=1"
    # 非默认端口保留；utm_ 前缀家族整体剔除
    assert canonical_url("http://x.com:8080/?utm_term=t&z=1") == "http://x.com:8080/?z=1"


# ── T65-1…T65-5 feed 解析（feedparser 裁决实现）─────────────────────


def test_t65_1_rss20_hugo_sample() -> None:
    parsed = rss.parse_feed(RSS2_BODY)
    assert parsed["feed_title"] == "Hugo 技术博客"
    first = parsed["items"][0]
    assert first["guid"] == "urn:uuid:1111-aaaa"  # guid 归一成功
    assert first["published"] == "2026-01-02T08:00:00Z"  # ISO
    assert first["author"] == "alice@example.com (Alice)"
    assert first["license"] == "CC-BY"  # cc:license 前缀推断
    assert "creativecommons.org/licenses/by" in first["license_note"]
    assert parsed["rejected"] == []


def test_t65_2_atom_github_releases_sample() -> None:
    parsed = rss.parse_feed(ATOM_BODY)
    entry = parsed["items"][0]
    assert entry["guid"] == "tag:github.com,2008:repository/123456/release/v1.0.0"
    assert entry["url"] == "https://github.com/owner/repo/releases/tag/v1.0.0"
    assert entry["published"].startswith("2026-01-02")  # 与 T65-1 同构字段断言


def test_t65_2b_jsonfeed_sample() -> None:
    """任务书容错面：JSON Feed（feedparser 原生不覆盖，json 路径映射）。"""
    parsed = rss.parse_feed(JSONFEED_BODY)
    assert parsed["feed_title"] == "JSON Feed 站点"
    assert [i["title"] for i in parsed["items"]] == ["JSON 条目一", "JSON 条目二"]
    assert parsed["items"][0]["author"] == "Bob"
    assert parsed["items"][0]["guid"] == "https://jf.example.com/1"


def test_t65_3_billion_lauchhs_dtd_rejected() -> None:
    """DTD/ENTITY 注入（billion-laughs）→ 安全门拒绝，零条目产出。"""
    evil = (
        '<?xml version="1.0"?><!DOCTYPE rss ['
        '<!ENTITY a "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa">'
        '<!ENTITY b "&a;&a;&a;&a;&a;&a;&a;&a;&a;&a;">]>'
        "<rss version=\"2.0\"><channel><title>x</title>"
        "<item><title>&b;</title><link>https://x.example.com/1</link></item>"
        "</channel></rss>"
    )
    with pytest.raises(rss.FeedParseError) as err:
        rss.parse_feed(evil)
    assert "DTD/ENTITY" in str(err.value) and "安全门拒绝" in str(err.value)


def test_t65_4_html_page_rejected_with_guide() -> None:
    with pytest.raises(rss.FeedParseError) as err:
        rss.parse_feed("<html><body><h1>不是 feed</h1></body></html>")
    assert "非 RSS 2.0/Atom 格式" in str(err.value)
    assert "换 Atom 链接" in str(err.value)


def test_t65_5_entry_missing_guid_link_rejected_per_entry() -> None:
    body = """<?xml version="1.0"?>
<rss version="2.0"><channel><title>三缺一</title>
<item><title>第一条</title><link>https://x.example.com/1</link></item>
<item><title>第二条（无 guid 无 link）</title><description>只有描述</description></item>
<item><title>第三条</title><guid>urn:uuid:3333</guid></item>
</channel></rss>"""
    parsed = rss.parse_feed(body)
    assert len(parsed["items"]) == 2  # 第 1/3 条照常产出（不整源失败）
    assert any("第 2 条" in r for r in parsed["rejected"])  # 错误含序号


def test_t65_8_max_items_truncates_head() -> None:
    items = "".join(
        f"<item><title>条目{i}</title><guid>urn:uuid:{i}</guid>"
        f"<link>https://x.example.com/{i}</link></item>"
        for i in range(1, 11)
    )
    body = f'<?xml version="1.0"?><rss version="2.0"><channel><title>十条</title>{items}</channel></rss>'
    parsed = rss.parse_feed(body, max_items=3)
    assert [i["title"] for i in parsed["items"]] == ["条目1", "条目2", "条目3"]  # 截首不尾
